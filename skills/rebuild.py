#!/usr/bin/env python3
"""
skills.rebuild — coverage-aware rebuild of the nutrition analysis.

Stdlib only. No pyfooda, no pandas, no network. Reads:

    data/purchases_enriched.csv   raw purchase rows (product_name, price, date, ...)
    skills/food_table.json        per-100g nutrient profiles + units

Writes:

    public/report.json            the analysis dataset
    public/index.html             mobile-first report (generated by report_html.py)

What differs from the legacy pipeline (skills/nutrition_report.py):

  1. Duplicate receipt images are collapsed; each transaction counts once.
  2. Quantity is re-derived from the printed product name ONLY. No 100 g
     fallback, no price->weight guess, no typical-unit-weight table.
  3. Volumes stay volumes. ml is never assumed to equal g.
  4. No 5x-DRV nutrient suppression. Suspicious density is reported, not deleted.
  5. No IQR outlier deletion of whole trips.
  6. Verified-wrong mappings are quarantined with a visible reason.
  7. Every headline number carries its own coverage figure.

Run:  python3 -m skills.rebuild
"""

