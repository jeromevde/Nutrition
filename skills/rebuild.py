# ── Receipt line classification ──────────────────────────────────────────────
# The legacy pipeline never classified line types, so receipt totals, loyalty
# balances and payment lines were counted as purchases. That inflated the row
# denominator (and put a 6096.00 loyalty-point balance into "spend").
_METADATA_PATTERNS = (
    r"^TOTAA?L", r"SOUS[- ]?TOTAL", r"SUBTOTAA?L", r"^TOT\b",
    r"SOLDE DE POINTS", r"\bPOINTS\b", r"PUNTEN",
    r"CHEQ", r"CHEQUE", r"BANCONTACT", r"MAESTRO", r"\bVISA\b", r"BETAALD",
    r"ESPECES", r"CONTANT", r"\bCASH\b", r"PAIEMENT", r"BETALING",
    r"\bBTW\b", r"\bTVA\b", r"\bTAX\b", r"\bHTVA\b",
    r"KORTING", r"REMISE", r"RISTOURNE", r"REDUCTION",
    r"^SN\s*\d", r"^GS\s*:", r"^EUR\b", r"CARTE\b", r"KLANTEN", r"XTRA",
    r"NOMBRE D ARTICLES", r"AANTAL ARTIKELEN", r"^A PAYER", r"TE BETALEN",
    r"^\d+[.,]?\d*\s*KG\s*X$", r"^\d{1,6}$", r"^$",
)
_METADATA_RE = re.compile("|".join(_METADATA_PATTERNS), re.I)


def classify_line(name: str, price: float | None) -> str:
    """'metadata' for totals / payment / loyalty lines, else 'product'."""
    text = (name or "").strip().upper()
    if not text:
        return "metadata"
    if _METADATA_RE.search(text):
        return "metadata"
    # A grocery line item above EUR 100 on a Belgian supermarket receipt is a
    # total or a payment instrument, not a product.
    if price is not None and price >= 100:
        return "metadata"
    return "product"


# ── Quantity parsing ─────────────────────────────────────────────────────────

_MULTIPACK = re.compile(
    r"(?<!\d)(\d{1,2})\s*[X\*]\s*(\d+(?:[.,]\d+)?)\s*(KG|GR?|ML|CL|L)(?![A-Z])",
    re.I,
)
_SINGLE = re.compile(
    r"(?<![\dX*])(\d+(?:[.,]\d+)?)\s*(KG|GR?|ML|CL|L)(?![A-Z])",
    re.I,
)

_MASS_TO_G = {"G": 1.0, "GR": 1.0, "KG": 1000.0}
_VOL_TO_ML = {"ML": 1.0, "CL": 10.0, "L": 1000.0}


def parse_quantity(name: str) -> dict:
    """Derive quantity from the printed label text only.

    Returns {kind, amount, unit, method, text} where kind is 'mass', 'volume'
    or 'unknown'. Multipacks are resolved before single-unit weights so that
    '6X33CL' yields 1980 ml and never 33 ml.
    """
    text = (name or "").upper().replace(" ", " ")

    m = _MULTIPACK.search(text)
    if m:
        count = int(m.group(1))
        value = float(m.group(2).replace(",", "."))
        unit = m.group(3).upper()
        if unit in _MASS_TO_G:
            return {"kind": "mass", "amount": count * value * _MASS_TO_G[unit],
                    "unit": "g", "method": "label_multipack", "text": m.group(0)}
        return {"kind": "volume", "amount": count * value * _VOL_TO_ML[unit],
                "unit": "ml", "method": "label_multipack", "text": m.group(0)}

    m = _SINGLE.search(text)
    if m:
        value = float(m.group(1).replace(",", "."))
        unit = m.group(2).upper()
        if unit in _MASS_TO_G:
            return {"kind": "mass", "amount": value * _MASS_TO_G[unit],
                    "unit": "g", "method": "label_single", "text": m.group(0)}
        return {"kind": "volume", "amount": value * _VOL_TO_ML[unit],
                "unit": "ml", "method": "label_single", "text": m.group(0)}

    return {"kind": "unknown", "amount": None, "unit": None,
            "method": "not_on_label", "text": None}


# ── Build ────────────────────────────────────────────────────────────────────

def load_food_table() -> tuple[dict, dict]:
    data = json.loads(FOOD_TABLE.read_text(encoding="utf-8"))
    return data["foods"], data["units"]


def build_items(foods: dict) -> list[dict]:
    """One record per receipt line, with full provenance for its exclusion.

    Two quantity tiers are kept side by side:
      observed  – read off the printed label ("190G", "6X33CL")
      declared  – the legacy pipeline's estimate (typical unit weight, price
                  guess, hand-entered grams). An estimate, not a measurement.
    The headline uses observed only; 'declared' drives the sensitivity view.
    """
    items: list[dict] = []
    with PURCHASES_CSV.open(encoding="utf-8") as fh:
        for raw in csv.DictReader(fh):
            src = raw["source_file"]
            name = (raw["product_name"] or "").strip()
            food = (raw["pyfooda_name"] or "").strip()
            action = raw["llm_action"]

            try:
                price = float(raw["price"])
            except (TypeError, ValueError):
                price = None

            try:
                legacy_g = float(raw.get("grams_in_name") or "")
            except (TypeError, ValueError):
                legacy_g = None

            line_type = classify_line(name, price)
            qty = parse_quantity(name)
            issues: list[str] = []

            duplicate_of = DUPLICATE_ALIASES.get(src)
            if duplicate_of:
                issues.append("duplicate_receipt")

            # Quantity used only in the "include estimates" sensitivity mode.
            declared_g = None
            if qty["kind"] != "mass" and legacy_g and legacy_g > 0:
                declared_g = legacy_g
                issues.append("quantity_estimated_not_observed")

            if line_type == "metadata":
                state = "receipt_metadata"
            elif action != "match" or not food:
                state = "not_food_or_unmatched"
            elif name in QUARANTINE:
                state = "quarantined"
                issues.append("bad_mapping")
            elif food not in foods:
                state = "no_food_record"
                issues.append("missing_food_record")
            elif qty["kind"] == "volume":
                state = "volume_no_density"
                issues.append("volume_without_official_density")
            elif qty["kind"] == "unknown":
                state = "quantity_unknown"
                issues.append("quantity_not_on_label")
            else:
                state = "usable"

            if state in ("usable", "quantity_unknown") and \
                    any(h in name.upper() for h in COMPOSITE_HINTS):
                issues.append("composite_matched_to_ingredient__review")

            live = not duplicate_of
            counts = state == "usable" and live
            # Estimated tier: usable rows plus rows rescued by a declared weight.
            counts_est = live and (
                counts or (state == "quantity_unknown" and declared_g is not None)
            )

            nutrients: dict[str, float] = {}
            nutrients_est: dict[str, float] = {}
            if food in foods and live:
                if counts:
                    scale = qty["amount"] / 100.0
                    nutrients = {n: v * scale for n, v in foods[food].items()}
                if counts_est:
                    grams = qty["amount"] if counts else declared_g
                    scale = grams / 100.0
                    nutrients_est = {n: v * scale for n, v in foods[food].items()}

            items.append({
                "source_file": src,
                "duplicate_of": duplicate_of,
                "date": raw["date"],
                "year": (raw["date"] or "")[:4],
                "product_name": name,
                "food": food if action == "match" else "",
                "price": price,
                "line_type": line_type,
                "qty": qty,
                "declared_g": declared_g,
                "state": state,
                "issues": issues,
                "nutrients": nutrients,
                "nutrients_est": nutrients_est,
                "counts": counts,
                "counts_est": counts_est,
            })
    return items


def coverage(items: list[dict]) -> dict:
    live = [i for i in items if not i["duplicate_of"]]
    meta = [i for i in live if i["line_type"] == "metadata"]
    prod = [i for i in live if i["line_type"] == "product"]
    food_rows = [i for i in prod if i["food"]and i["state"] != "not_food_or_unmatched"]
    usable = [i for i in prod if i["counts"]]
    usable_est = [i for i in prod if i["counts_est"]]

    def pct(a, b):
        return round(100.0 * a / b, 1) if b else 0.0

    spend_all = sum(i["price"] or 0.0 for i in prod)
    spend_usable = sum(i["price"] or 0.0 for i in usable)
    spend_usable_est = sum(i["price"] or 0.0 for i in usable_est)

    by_state: dict[str, int] = defaultdict(int)
    for i in live:
        by_state[i["state"]] += 1

    return {
        "rows_total_raw": len(items),
        "rows_dropped_as_duplicate": len(items) - len(live),
        "rows_receipt_metadata": len(meta),
        "rows_product_lines": len(prod),
        "rows_food_matched": len(food_rows),
        "rows_usable": len(usable),
        "rows_usable_with_estimates": len(usable_est),
        "pct_matched": pct(len(food_rows), len(prod)),
        "pct_quantity_of_matched": pct(len(usable), len(food_rows)),
        "pct_usable_of_all": pct(len(usable), len(prod)),
        "pct_usable_of_all_with_estimates": pct(len(usable_est), len(prod)),
        "spend_total_eur": round(spend_all, 2),
        "spend_usable_eur": round(spend_usable, 2),
        "pct_spend_covered": pct(spend_usable, spend_all),
        "pct_spend_covered_with_estimates": pct(spend_usable_est, spend_all),
        "by_state": dict(by_state),
    }


def nutrient_density(items: list[dict], year: str | None = None,
                     mode: str = "observed") -> dict:
    """Density on the covered subset:  sum(nutrient) / sum(energy) * 2500.

    Each nutrient uses only rows where BOTH energy and that nutrient are known,
    so every figure carries its own denominator.

    mode='observed'  quantities read off the label only (headline)
    mode='estimated' also includes legacy estimated weights (sensitivity)
    """
    key = "nutrients" if mode == "observed" else "nutrients_est"
    flag = "counts" if mode == "observed" else "counts_est"
    pool = [i for i in items if i[flag] and i[key].get("Energy")]
    if year:
        pool = [i for i in pool if i["year"] == year]

    total_energy = sum(i[key]["Energy"] for i in pool)
    out: dict[str, dict] = {}
    if total_energy <= 0:
        return out

    for nut in NUTRIENT_ORDER:
        rows = [i for i in pool if nut in i[key]]
        if not rows:
            continue
        nut_energy = sum(i[key]["Energy"] for i in rows)
        amount = sum(i[key][nut] for i in rows)
        cov = 100.0 * nut_energy / total_energy
        value = amount / nut_energy * KCAL_NORM if nut_energy else None

        ref = REFERENCE.get(nut)
        top = sorted(rows, key=lambda i: i[key][nut], reverse=True)[:5]
        top_share = (top[0][key][nut] / amount * 100.0) if amount else 0.0

        out[nut] = {
            "value": round(value, 2) if value is not None else None,
            "coverage_pct": round(cov, 1),
            "reference": round(ref, 2) if ref else None,
            "reference_kind": REFERENCE_KIND.get(nut),
            "pct_of_reference": round(value / ref * 100, 1) if (ref and value) else None,
            "scored": bool(ref) and cov >= 80.0,
            "top_contributors": [
                {
                    "product_name": i["product_name"],
                    "food": i["food"],
                    "date": i["date"],
                    "amount": round(i[key][nut], 2),
                    "share_pct": round(i[key][nut] / amount * 100, 1) if amount else 0.0,
                }
                for i in top
            ],
            "dominated_by_single_item": top_share >= 25.0,
            "top_item_share_pct": round(top_share, 1),
        }
    out["_energy_pool_rows"] = len(pool)
    return out


def receipts_summary(items: list[dict]) -> dict:
    delhaize = ROOT / "data" / "delhaize"
    images = sorted(p.name for p in delhaize.glob("*.jpg")) if delhaize.exists() else []
    csvs = sorted(p for p in delhaize.glob("*.csv")) if delhaize.exists() else []
    empty = [p.name for p in csvs
             if len([l for l in p.read_text(encoding="utf-8", errors="replace").splitlines() if l.strip()]) <= 1]
    with_csv = {p.stem for p in csvs}
    no_ocr = sorted(n[:-4] for n in images if n[:-4] not in with_csv)

    in_analysis = sorted({i["source_file"] for i in items if not i["duplicate_of"]})
    return {
        "images_total": len(images),
        "images_unique": len(images) - len(DUPLICATE_ALIASES),
        "duplicate_pairs": len(DUPLICATE_ALIASES),
        "ocr_csv_files": len(csvs),
        "ocr_empty": empty,
        "images_without_ocr": no_ocr,
        "receipts_in_analysis": len(in_analysis),
        "date_first": min((i["date"] for i in items if i["date"]), default=None),
        "date_last": max((i["date"] for i in items if i["date"]), default=None),
    }


