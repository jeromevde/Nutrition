def status(cov: dict, nutrients: dict, receipts: dict) -> tuple[str, dict]:
    headline_low = [n for n, d in nutrients.items()
                    if isinstance(d, dict) and d.get("coverage_pct", 0) < 80]

    reasons: dict[str, list[str]] = {}
    for lang in ("en", "fr", "it"):
        out: list[str] = []
        if cov["pct_usable_of_all"] < 60:
            out.append(_REASON_TEMPLATES["usable"][lang].format(p=cov["pct_usable_of_all"]))
        if headline_low:
            names = ", ".join(_NUTRIENT_NAMES[lang].get(x, x) for x in headline_low)
            out.append(_REASON_TEMPLATES["lowcov"][lang].format(n=len(headline_low), list=names))
        out.append(_REASON_TEMPLATES["unverified"][lang])
        out.append(_REASON_TEMPLATES["backlog"][lang].format(
            a=len(receipts["images_without_ocr"]), b=len(receipts["ocr_empty"])))
        reasons[lang] = out

    if cov["pct_usable_of_all"] >= 85 and not headline_low:
        return "Beta", reasons
    return "Draft", reasons


def main() -> None:
    foods, units = load_food_table()
    items = build_items(foods)
    cov = coverage(items)

    years = sorted({i["year"] for i in items if i["year"]})
    nutrients_all = nutrient_density(items)
    nutrients_est = nutrient_density(items, mode="estimated")
    by_year = {y: nutrient_density(items, y) for y in years}
    by_year_est = {y: nutrient_density(items, y, mode="estimated") for y in years}

    # How much does each headline number depend on estimated (not observed)
    # quantities? Large gaps mean the figure is carried by guesses.
    sensitivity = []
    for nut in NUTRIENT_ORDER:
        a = nutrients_all.get(nut, {}).get("value")
        b = nutrients_est.get(nut, {}).get("value")
        if a and b:
            sensitivity.append({
                "nutrient": nut,
                "observed_only": a,
                "with_estimates": b,
                "delta_pct": round((b - a) / a * 100, 1),
            })
    sensitivity.sort(key=lambda d: -abs(d["delta_pct"]))

    rec = receipts_summary(items)
    state, reasons = status(cov, nutrients_all, rec)

    quarantined = defaultdict(lambda: {"rows": 0, "reason": "", "spend": 0.0})
    for i in items:
        if i["state"] == "quarantined" and not i["duplicate_of"]:
            q = quarantined[i["product_name"]]
            q["rows"] += 1
            q["reason"] = QUARANTINE[i["product_name"]]
            q["spend"] = round(q["spend"] + (i["price"] or 0.0), 2)

    unresolved = defaultdict(lambda: {"rows": 0, "state": "", "spend": 0.0})
    for i in items:
        if not i["duplicate_of"] and i["line_type"] == "product" and i["state"] in (
            "not_food_or_unmatched", "quantity_unknown", "volume_no_density"
        ):
            u = unresolved[i["product_name"]]
            u["rows"] += 1
            u["state"] = i["state"]
            u["spend"] = round(u["spend"] + (i["price"] or 0.0), 2)

    review = defaultdict(int)
    for i in items:
        if "composite_matched_to_ingredient__review" in i["issues"] and i["counts"]:
            review[f"{i['product_name']} -> {i['food']}"] += 1

    report = {
        "generated_from": "data/purchases_enriched.csv (legacy OCR snapshot)",
        "kcal_normalisation": KCAL_NORM,
        "status": state,
        "status_reasons_i18n": reasons,
        "disclaimer_i18n": DISCLAIMER,
        "disclaimer": (
            "Questo report descrive la composizione nutrizionale della SPESA "
            "ACQUISTATA da Delhaize, normalizzata a 2.500 kcal. Non misura ciò che "
            "qualcuno ha mangiato: scarti, scorte in dispensa, pasti fuori casa e i "
            "due negozi non ancora inclusi (Carrefour, Colruyt) non sono considerati."
        ),
        "nutrient_labels": NUTRIENT_IT,
        "receipts": rec,
        "coverage": cov,
        "years": years,
        "nutrients": nutrients_all,
        "nutrients_estimated": nutrients_est,
        "nutrients_by_year": by_year,
        "nutrients_by_year_estimated": by_year_est,
        "sensitivity_estimated_quantities": sensitivity,
        "units": units,
        "nutrient_order": NUTRIENT_ORDER,
        "no_reference": sorted(_NO_REFERENCE),
        "quarantined": [
            {"product_name": k, **v}
            for k, v in sorted(quarantined.items(), key=lambda kv: -kv[1]["rows"])
        ],
        "unresolved": [
            {"product_name": k, **v}
            for k, v in sorted(unresolved.items(), key=lambda kv: -kv[1]["spend"])[:120]
        ],
        "needs_review": [
            {"mapping": k, "rows": v}
            for k, v in sorted(review.items(), key=lambda kv: -kv[1])[:60]
        ],
        "items": [
            {
                "date": i["date"], "product_name": i["product_name"],
                "food": i["food"], "price": i["price"],
                "qty_amount": round(i["qty"]["amount"], 1) if i["qty"]["amount"] else None,
                "qty_unit": i["qty"]["unit"], "qty_method": i["qty"]["method"],
                "declared_g": i["declared_g"],
                "line_type": i["line_type"],
                "state": i["state"], "issues": i["issues"],
                "energy": round(i["nutrients"].get("Energy", 0), 1) or None,
            }
            # Receipt-metadata rows are included so the `receipt_metadata` state
            # filter has something to show; they carry no nutrients.
            for i in items if not i["duplicate_of"]
        ],
    }

    PUBLIC_DIR.mkdir(exist_ok=True)
    out = PUBLIC_DIR / "report.json"
    out.write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf-8")

    print(f"status              {state}")
    print(f"receipts analysed   {report['receipts']['receipts_in_analysis']}"
          f"  (of {report['receipts']['images_total']} images,"
          f" {report['receipts']['images_unique']} unique)")
    print(f"rows dropped (dup)  {cov['rows_dropped_as_duplicate']}")
    print(f"rows receipt meta   {cov['rows_receipt_metadata']}  (totals/points/payment)")
    print(f"rows product lines  {cov['rows_product_lines']}")
    print(f"matched             {cov['pct_matched']}%")
    print(f"quantity/matched    {cov['pct_quantity_of_matched']}%")
    print(f"usable rows         {cov['pct_usable_of_all']}%"
          f"   (with estimates {cov['pct_usable_of_all_with_estimates']}%)")
    print(f"spend covered       {cov['pct_spend_covered']}%  "
          f"(EUR {cov['spend_usable_eur']} of {cov['spend_total_eur']})")
    print(f"row states          {cov['by_state']}")
    if sensitivity:
        worst = sensitivity[0]
        print(f"most estimate-driven {worst['nutrient']}: "
              f"{worst['observed_only']} -> {worst['with_estimates']} "
              f"({worst['delta_pct']:+}%)")
    print(f"-> {out}")


